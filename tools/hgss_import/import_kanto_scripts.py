    def write_visible_items(self):
        path = SCRIPTS / "scripts_visible_items.s"
        lines = path.read_text().splitlines()
        lines = [l for l in lines if "VisibleItems_Kanto_" not in l]
        text = "\n".join(lines)
        text = re.sub(r"\n\nVisibleItems_Kanto_\w+:\n(    .*\n)+", "\n", text)
        lines = text.splitlines()
        end = lines.index("    ScriptEntryEnd")
        lines[end:end] = [f"    ScriptEntry {label}" for label, _, _ in self.visible_items]
        body = []
        for label, item, qty in self.visible_items:
            body += ["", f"{label}:", f"    SetVar VAR_0x8008, {item}", f"    SetVar VAR_0x8009, {qty}",
                     "    GoTo VisibleItems_TryGiveItem", "    End"]
        at = len(lines) - 1 if lines[-1].strip() == ".balign 4, 0" else len(lines)
        while at > 0 and not lines[at - 1].strip():
            at -= 1
        lines[at:at] = body
        path.write_text("\n".join(lines) + "\n")

    def count_visible_items(self):
        text = (SCRIPTS / "scripts_visible_items.s").read_text()
        return len([l for l in text.splitlines() if l.startswith("    ScriptEntry ") and "Kanto" not in l])

