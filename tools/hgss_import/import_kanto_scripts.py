    def write_marts(self):
        hg = (self.hg / "src/scrcmd_mart.c").read_text()
        lists = dict(re.findall(r"const u16 (_\w+)\[\] = \{([^}]*)\}", hg))
        order = re.search(r"const u16 \*_0210FA3C\[\] = \{([^}]*)\}", hg).group(1).replace(",", " ").split()
        ids = read_lines(PL / "generated/mart_specialties_id.txt")
        ids = [i for i in ids if not i.startswith("MART_SPECIALTIES_ID_KANTO_")]
        defs, entries = [], []
        for n in sorted(self.names.marts):
            items = [i.strip() for i in lists[order[n]].split(",") if i.strip() and i.strip() != "0xFFFF"]
            items = [i for i in (self.pl_item(i) for i in items) if i]
            defs.append(f"static const u16 sKantoMart{n}[] = {{ {', '.join(items + ['SHOP_ITEM_END'])} }};")
            entries.append(f"    [{self.names.marts[n]}] = sKantoMart{n}, \\")
            ids.append(self.names.marts[n])
        (PL / "generated/mart_specialties_id.txt").write_text("\n".join(ids) + "\n")
        (PL / "include/data/kanto_marts.h").write_text(
            "// Generated by tools/hgss_import/import_kanto_scripts.py, do not edit.\n"
            "// Kanto's specialty marts, from HGSS.\n\n" + "\n".join(defs) + "\n\n#define KANTO_MART_SPECIALTIES \\\n"
            + "\n".join(entries) + "\n\n")

    def write_new_game_flags(self):
        """Kanto's flags that HGSS sets when a game starts."""
        text = (self.hg / "files/fielddata/script/scr_seq/scr_seq_0149.s").read_text()
        sets = []
        for flag in re.findall(r"SetFlag (FLAG_\w+)", text):
            if flag in self.names.flag_map and self.names.flag_map[flag] != "0":
                sets.append(f"    SetFlag {self.names.flag_map[flag]}")
        path = SCRIPTS / "scripts_init_new_game.s"
        lines = path.read_text().splitlines()
        if GENERATED_BEGIN in lines:
            del lines[lines.index(GENERATED_BEGIN):lines.index(GENERATED_END) + 1]
        end = max(i for i, l in enumerate(lines) if l.strip() == "End")
        lines[end:end] = [GENERATED_BEGIN] + sets + [GENERATED_END]
        path.write_text("\n".join(lines) + "\n")

    def update_headers(self):
        path = PL / "include/data/kanto_map_headers.h"
        text = path.read_text()
        for h in self.kanto:
            start = text.index(f"    [{header_name(h['name'])}] = {{")
            end = text.index("    },", start)
            entry = text[start:end]
            entry = re.sub(r"\.scriptsArchiveID = \w+,", f".scriptsArchiveID = {self.script_files[h['name']]},", entry)
            entry = re.sub(r"\.initScriptsArchiveID = \w+,", f".initScriptsArchiveID = {self.init_files[h['name']]},", entry)
            entry = re.sub(r"\.msgArchiveID = \w+,", f".msgArchiveID = {kanto_text.bank_const(kanto_text.gmm_name(h['msgBank']))},", entry)
            text = text[:start] + entry + text[end:]
        path.write_text(text)

