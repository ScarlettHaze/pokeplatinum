def read_lines(path):
    return [l.strip() for l in path.read_text().splitlines() if l.strip()]


def pl_constants():
    """Identifiers Platinum's script macros know (approximately)."""
    names = set()
    inc = (PL / "asm/macros/scrcmd.inc").read_text()
    for m in re.finditer(r'#include "generated/(\w+)\.h"', inc):
        path = PL / "generated" / f"{m.group(1)}.txt"
        if path.exists():
            names |= {l.split("=")[0].strip() for l in read_lines(path)}
    for m in re.finditer(r'#include "(constants/[\w/]+\.h)"', inc):
        path = PL / "include" / m.group(1)
        if path.exists():
            text = path.read_text()
            names |= set(re.findall(r"#define\s+(\w+)", text))
            names |= set(re.findall(r"^\s+([A-Z][A-Z0-9_]+)\s*[,=]", text, re.M))
    names |= {l.split("=")[0].strip() for l in read_lines(PL / "generated/vars_flags.txt")}
    names |= {l for l in read_lines(PL / "generated/species.txt")}
    return names


def pl_vars_flags():
    """Platinum's flag and var names by number (the first name of each)."""
    values, by_value, current = {}, {}, 0
    for line in read_lines(PL / "generated/vars_flags.txt"):
        name, _, value = (p.strip() for p in line.partition("="))
        if value and not name.startswith(("FLAG_", "VAR_")) and value.startswith(("FLAG_", "VAR_")):
            # An end marker naming the last flag or var.
            values[name] = values[value]
            continue
        if value:
            current = int(value) if value.isdigit() else values[value]
        values[name] = current
        if name.startswith(("FLAG_", "VAR_")):
            by_value.setdefault(current, name)
            current += 1
    return by_value


def hgss_defines(path):
    out = {}
    for line in path.read_text().splitlines():
        m = re.match(r"#define\s+(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b", line)
        if m:
            out[m.group(1)] = int(m.group(2), 0)
    return out


class Names:
    """Translates the names HGSS's scripts and events use."""

    def __init__(self, hg, kanto_sprites, free):
        self.hg = hg
        self.known = pl_constants()
        self.flags = hgss_defines(hg / "include/constants/flags.h")
        self.vars = hgss_defines(hg / "include/constants/vars.h")
        self.sprites = kanto_sprites
        self.sounds = self.read_sounds()
        self.free_flags = list(free["flags"])
        self.free_vars = list(free["vars"])
        self.free_daily = [f for f in read_lines(PL / "generated/vars_flags.txt") if re.fullmatch(r"FLAG_DAILY_0x[0-9A-F]+", f)]
        self.flag_map, self.var_map = {}, {}
        self.pl_names = pl_vars_flags()
        self.fly_flags = self.read_fly_flags()
        self.messages = set()
        self.objects = set()
        self.marts = {}
        self.unsupported_names = collections.Counter()
        self.badges = hgss_defines(hg / "include/constants/badge.h")
        self.kanto_maps = {}  # HGSS map -> (Platinum header, on the world map)

    @staticmethod
    def read_sounds():
        """Sequence name -> the constant scripts use, which names its file."""
        seqs = json.loads((PL / "res/sound/pl_sound_data.json").read_text())["seqInfo"]
        naix = PL / "build/res/sound/pl_sound_data.naix"
        by_id = {int(v): k for k, v in re.findall(r"#define (\w+) (\d+)", naix.read_text())}
        return {s["name"]: by_id[i] for i, s in enumerate(seqs) if s.get("name") and i in by_id}

    def read_fly_flags(self):
        text = (PL / "src/applications/town_map/fly_locations.c").read_text()
        pairs = re.findall(r"\.mapHeader = (MAP_HEADER_KANTO_\w+),\s*\.unusedUnlockFirstArrivalFlag = (FIRST_ARRIVAL_\w+)", text)
        return {h.removeprefix("MAP_HEADER_KANTO_"): "FLAG_" + f for h, f in pairs}

    # ------------------------------------------------------------- flags/vars
    def flag(self, name):
        if name in self.flag_map:
            return self.flag_map[name]
        value = self.flags.get(name)
        if value is None:
            raise Unsupported(name)
        if value == 0:
            out = "0"
        elif value < 0x40:
            out = self.pl_names[value]
        elif 0xAA0 <= value < 0xAA0 + 192:
            out = self.free_daily.pop()
        elif name == "FLAG_GAME_CLEAR":
            out = "FLAG_GAME_COMPLETED"
        elif name.startswith("FLAG_SYS_FLYPOINT_") and name.removeprefix("FLAG_SYS_FLYPOINT_") in self.fly_flags:
            out = self.fly_flags[name.removeprefix("FLAG_SYS_FLYPOINT_")]
        elif 0x550 <= value < 0x830:
            raise Unsupported(f"trainer flag {name}")
        else:
            if not self.free_flags:
                raise Unsupported(f"out of flags for {name}")
            out = self.free_flags.pop(0)
        self.flag_map[name] = out
        return out

    def var(self, name):
        if name in self.var_map:
            return self.var_map[name]
        value = self.vars.get(name)
        if value is None:
            raise Unsupported(name)
        if 0x4000 <= value < 0x4020:
            out = self.pl_names[value]
        elif 0x4020 <= value < 0x4030:
            out = self.pl_names[value]
        elif name == "VAR_SPECIAL_RESULT":
            out = "VAR_RESULT"
        elif name == "VAR_SPECIAL_LAST_TALKED":
            out = "VAR_LAST_TALKED"
        elif 0x8000 <= value <= 0x800B:
            out = f"VAR_0x{value:04X}"
        elif 0x4030 <= value < 0x8000:
            if not self.free_vars:
                raise Unsupported(f"out of vars for {name}")
            out = self.free_vars.pop(0)
        else:
            raise Unsupported(name)
        self.var_map[name] = out
        return out

    # ------------------------------------------------------------------ names
    def value(self, token):
        token = token.strip()
        if re.fullmatch(r"-?(0x[0-9A-Fa-f]+|\d+)", token):
            return token
        if re.fullmatch(r"\w+", token):
            return self.name(token)
        # An expression: translate each name in it.
        return re.sub(r"[A-Za-z_]\w*", lambda m: self.name(m.group(0)), token)

    def name(self, n):
        if n.startswith("FLAG_"):
            return self.flag(n)
        if n.startswith("VAR_"):
            return self.var(n)
        if n == "obj_player":
            return "LOCALID_PLAYER"
        if n.startswith("obj_"):
            if n not in self.objects:
                raise Unsupported(n)
            return n
        if n.startswith("msg_"):
            return self.message(n)
        if n.startswith("SPRITE_"):
            gfx = self.sprites.get(n)
            if n.startswith("SPRITE_VAR_"):
                gfx = f"OBJ_EVENT_GFX_VAR_{int(n.removeprefix('SPRITE_VAR_')):X}"
            if gfx is None:
                raise Unsupported(n)
            return gfx
        if n == "RGB_BLACK":
            return "COLOR_BLACK"
        if n == "RGB_WHITE":
            return "COLOR_WHITE"
        if n in ("TRUE", "FALSE"):
            return n
        if n.startswith(("MAP_", "TRAINER_", "BADGE_")):
            raise Unsupported(n)
        if n in self.known:
            return n
        self.unsupported_names[n] += 1
        raise Unsupported(n)

    def message(self, m):
        if re.fullmatch(r"\d+", m):
            return m
        if m not in self.messages:
            raise Unsupported(f"message {m}")
        return m

    def sound(self, s):
        return self.sounds.get(s)

    def fanfare(self, s):
        f = FANFARES.get(s)
        return self.sounds.get(f)

    def badge_number(self, b):
        if re.fullmatch(r"\d+|0x[0-9a-fA-F]+", b):
            return int(b, 0)
        return self.badges.get(b)

    def badge(self, b):
        """HGSS's badges 8 to 15 are Kanto's; Platinum has 8."""
        value = self.badge_number(b)
        if value is None or not 8 <= value < 16:
            raise Unsupported(f"badge {b}")
        return str(value - 8)

    def badge_check(self, b, var):
        value = self.badge_number(b)
        if value is not None and value < 8:
            # Johto's badges: HGSS's player has them all in Kanto.
            return [f"SetVar {var}, 1"]
        return [f"CheckBadgeAcquired {self.badge(b)}, {var}"]

    def trainer(self, t):
        raise Unsupported(f"trainer {t}")

    def mart(self, n):
        self.marts[n] = f"MART_SPECIALTIES_ID_KANTO_{n}"
        return self.marts[n]

    def warp(self, args):
        """Warp map, 0, x, z, direction (HGSS) -> Warp header, x, z, direction."""
        if args[0] not in self.kanto_maps:
            raise Unsupported(f"warp to {args[0]}")
        header, world = self.kanto_maps[args[0]]
        out = []
        coords = []
        for value, offset in ((args[2], WORLD_OFFSET_X), (args[3], WORLD_OFFSET_Z)):
            if not world:
                coords.append(self.value(value))
            elif re.fullmatch(r"\d+", value):
                coords.append(str(int(value) - offset))
            else:
                var = self.value(value)
                out.append(f"SubVar {var}, {offset}")
                coords.append(var)
        return out + [f"Warp {header}, {coords[0]}, {coords[1]}, {self.value(args[4])}"]


