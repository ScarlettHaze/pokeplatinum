class ScriptsImporter:
    def __init__(self, hg):
        self.hg = Path(hg)
        headers = load_headers(self.hg)
        self.kanto = [h for h in headers if h["regionNo"] == "MAP_REGION_KANTO"]
        self.sprites = json.loads((HERE / "kanto_sprites.json").read_text())
        self.free = self.free_vars_flags()
        self.names = Names(self.hg, {k: v for k, v in self.sprites.items() if v}, self.free)
        self.names.kanto_maps = {h["name"]: (header_name(h["name"]), matrix_key(h["matrixId"]) == "0000_EVERYWHERE") for h in self.kanto}
        self.translator = Translator(self.names)
        self.hidden_items = self.read_hidden_items()
        self.item_balls = self.read_item_balls()
        self.items = set(read_lines(PL / "generated/items.txt"))
        self.hgss_items = {v: k for k, v in hgss_defines(self.hg / "include/constants/items.h").items() if k.startswith("ITEM_")}
        self.visible_items = []   # (label, item, quantity)
        self.kanto_hidden = []    # (item, quantity)

    # ------------------------------------------------------------ free names
    def free_vars_flags(self):
        """Platinum flags and vars that only Sinnoh's map scripts and events use."""
        lines = read_lines(PL / "generated/vars_flags.txt")
        hdr = (PL / "include/data/map_headers.h").read_text()
        sinnoh = set(re.findall(r"(?:scriptsArchiveID|initScriptsArchiveID) = (scripts_\w+)", hdr))
        sinnoh_events = set(re.findall(r"eventsArchiveID = (events_\w+)", hdr))
        live = collections.Counter()
        for root in ("src", "include", "asm", "res"):
            for path in (PL / root).rglob("*"):
                if not path.is_file() or path.suffix not in (".c", ".h", ".s", ".inc", ".json", ".txt", ".py"):
                    continue
                stem = path.stem
                if path.suffix == ".s" and "field/scripts" in str(path) and (stem in sinnoh or "kanto" in stem):
                    continue
                if path.suffix == ".json" and "field/events" in str(path) and (stem in sinnoh_events or stem.startswith("kanto_")):
                    continue
                if path.name in ("map_headers.h", "kanto_map_headers.h", "hidden_items.h"):
                    continue
                for m in re.findall(r"\b(?:FLAG|VAR)_\w+", path.read_text(errors="ignore")):
                    live[m] += 1
        start = lines.index(next(l for l in lines if l.startswith("MAP_LOCAL_FLAGS_END")))
        end = lines.index(next(l for l in lines if l.startswith("HIDDEN_ITEM_FLAGS_START")))
        flags = [l for l in lines[start + 1:end] if l.startswith("FLAG_") and "=" not in l and live[l] == 0 and not RESERVED.search(l)]
        vstart = lines.index(next(l for l in lines if l.startswith("MAP_LOCAL_VARS_END")))
        vend = lines.index(next(l for l in lines if l.startswith("SCRIPT_LOCAL_VARS_START")))
        vars_ = [l for l in lines[vstart + 1:vend] if l.startswith("VAR_") and "=" not in l and live[l] == 0
                 and not RESERVED.search(l) and not l.startswith("VAR_OBJ_GFX")]
        return {"flags": flags, "vars": vars_}

    # -------------------------------------------------------------- HGSS data
    def read_hidden_items(self):
        text = (self.hg / "src/data/fieldmap/hidden_items.h").read_text()
        return [(m.group(1), int(m.group(2))) for m in re.finditer(r"\{\s*(ITEM_\w+),\s*(\d+),[^}]*\}", text)]

    def read_item_balls(self):
        """std_itemball_* (7000 + n) -> (item ID, quantity), from scr_seq_0141."""
        text = (self.hg / "files/fielddata/script/scr_seq/scr_seq_0141.s").read_text()
        out = {}
        for m in re.finditer(r"scr_seq_0141_(\d+):\n\tSetVar VAR_SPECIAL_x8008, (\w+)\n\tSetVar VAR_SPECIAL_x8009, (\w+)", text):
            out[int(m.group(1))] = (m.group(2), int(m.group(3), 0))
        return out

    def std_ids(self):
        return hgss_defines(self.hg / "include/constants/std_script.h")

    def pl_item(self, item):
        """HGSS item (name or ID) -> Platinum item name, or None."""
        name = self.hgss_items.get(int(item)) if item.isdigit() else item
        return name if name in self.items else None

    # ----------------------------------------------------------------- events
    def import_events(self):
        std = self.std_ids()
        self.entry_kinds = collections.defaultdict(dict)  # events bank -> {script number: kind}
        self.objects_by_bank = {}
        self.event_report = collections.Counter()
        for bank in sorted({h["eventsBank"] for h in self.kanto}):
            world = any(h["eventsBank"] == bank and matrix_key(h["matrixId"]) == "0000_EVERYWHERE" for h in self.kanto)
            dx, dz = (WORLD_OFFSET_X, WORLD_OFFSET_Z) if world else (0, 0)
            src = self.hg / "files/fielddata/eventdata/zone_event" / (bank.removeprefix("NARC_zone_event_").removesuffix("_bin") + ".json")
            hg_events = json.loads(src.read_text())
            path = EVENTS / f"{events_name(bank)}.json"
            events = json.loads(path.read_text())
            kinds = self.entry_kinds[bank]
            objects = []
            for o in hg_events.get("objects", []):
                objects.append(self.object_event(o, dx, dz, std, kinds))
            self.objects_by_bank[bank] = [o["id"] for o in objects]
            bgs = [b for b in (self.bg_event(b, dx, dz, std, kinds) for b in hg_events.get("bgs", [])) if b]
            coords = []
            for c in hg_events.get("coords", []):
                script = self.script_number(c["scriptId"])
                kinds.setdefault(script, "coord")
                try:
                    var = self.names.var(c["var"])
                except Unsupported:
                    self.event_report["coord with unsupported var"] += 1
                    continue
                coords.append({"script": script, "x": c["x"] - dx, "z": c["z"] - dz, "y": c["y"],
                               "width": c["w"], "length": c["h"], "var": var, "value": c["val"]})
            events.update({"object_events": objects, "bg_events": bgs, "coord_events": coords})
            path.write_text(json.dumps(events, indent=4) + "\n")

    @staticmethod
    def script_number(script_id):
        m = re.fullmatch(r"_EV_scr_seq_\w+_(\d+) \+ 1", str(script_id))
        return int(m.group(1)) + 1 if m else None

    def object_event(self, o, dx, dz, std, kinds):
        script_id = str(o["scriptId"])
        script = self.script_number(script_id)
        trainer_type = "TRAINER_TYPE_NONE"
        sprite = o["spriteId"]
        if script is not None:
            kinds.setdefault(script, "object")
        elif script_id in FIELD_MOVE_OBJECTS:
            script = FIELD_MOVE_OBJECTS[script_id]
        elif script_id.startswith("std_itemball_"):
            script = self.item_ball(std[script_id] - 7000, script_id)
        else:
            # Trainers, apricorn trees and the Pokémon Center's link NPCs.
            self.event_report[f"object with {script_id.split('(')[0]}"] += 1
            script = 0
        try:
            gfx = self.names.name(sprite)
        except Unsupported:
            self.event_report[f"sprite {sprite}"] += 1
            gfx = "OBJ_EVENT_GFX_KANTO_GSMAN1" if "OBJ_EVENT_GFX_KANTO_GSMAN1" in self.sprites.values() else "OBJ_EVENT_GFX_PLAYER_M"
        try:
            flag = self.names.flag(o["eventFlag"])
        except Unsupported:
            self.event_report[f"object flag {o['eventFlag']}"] += 1
            flag = "0"
        movement = o["movement"] if o["movement"] <= LAST_SHARED_MOVEMENT_TYPE else 15
        params = [o["param0"], o["param1"], o["param2"]]
        return {
            "id": o["id"],
            "graphics_id": gfx,
            "movement_type": MOVEMENT_TYPES[movement],
            "trainer_type": trainer_type,
            "hidden_flag": flag,
            "script": script,
            "initial_dir": o["facingDirection"],
            "data": params if any(params) else [],
            "movement_range_x": o["xRange"],
            "movement_range_z": o["yRange"],
            "x": o["x"] - dx,
            "z": o["z"] - dz,
            "y": o["y"] >> 16,  # HGSS stores it as fixed point
        }

    def bg_event(self, b, dx, dz, std, kinds):
        script_id = str(b["scriptId"])
        script = self.script_number(script_id)
        if script is not None:
            kinds.setdefault(script, "bg")
            bg_type = 1 if b["type"] == 1 else 0
        elif script_id.startswith("std_hiddenitem_"):
            script = self.hidden_item(std[script_id] - 8000)
            if script is None:
                return None
            bg_type = 2
        else:
            self.event_report[f"bg with {script_id}"] += 1
            return None
        return {"script": script, "type": bg_type, "x": b["x"] - dx, "z": b["z"] - dz, "y": b["y"],
                "player_facing_dir": BG_DIRS[b["dir"]]}

    def item_ball(self, n, std_name):
        item, qty = self.item_balls[n]
        item = self.pl_item(item)
        if item is None:
            self.event_report["item ball with an item Platinum lacks"] += 1
            return 0
        label = "VisibleItems_Kanto_" + "".join(w.capitalize() for w in std_name.removeprefix("std_itemball_").split("_"))
        self.visible_items.append((label, item, qty))
        return 7000 + self.first_visible_kanto + len(self.visible_items) - 1

    def hidden_item(self, n):
        item, qty = self.hidden_items[n]
        item = self.pl_item(item)
        if item is None:
            self.event_report["hidden item Platinum lacks"] += 1
            return None
        self.kanto_hidden.append((item, qty))
        return 8000 + len(self.kanto_hidden) - 1

    # ---------------------------------------------------------------- scripts
    def import_scripts(self):
        names, init_names = [], []
        self.script_files = {}
        for bank in sorted({h["scriptsBank"] for h in self.kanto}):
            hs = [h for h in self.kanto if h["scriptsBank"] == bank]
            h = hs[0]
            stem = bank.removeprefix("NARC_scr_seq_").removesuffix("_bin")
            gmm = kanto_text.gmm_name(h["msgBank"])
            self.names.messages = self.messages[gmm]
            self.names.objects = set(self.objects_by_bank.get(h["eventsBank"], []))
            world = matrix_key(h["matrixId"]) == "0000_EVERYWHERE"
            ctx = FileContext(stem, (WORLD_OFFSET_X, WORLD_OFFSET_Z) if world else (0, 0), self.entry_kinds[h["eventsBank"]])
            text = (self.hg / "files/fielddata/script/scr_seq" / f"{stem}.s").read_text()
            body, good, stand_ins = self.translator.translate_file(text, ctx)
            name = f"kanto_scripts_{stem.removeprefix('scr_seq_').lower()}"
            includes = ['#include "macros/scrcmd.inc"', f'#include "res/text/bank/{kanto_text.bank_name(gmm)}.h"',
                        f'#include "res/field/events/{events_name(h["eventsBank"])}.h"', "", ""]
            (SCRIPTS / f"{name}.s").write_text("\n".join(includes + body) + "\n")
            names.append(name)
            for hh in hs:
                self.script_files[hh["name"]] = name
            self.stats["entries"] += good
            self.stats["stand-ins"] += stand_ins
        self.init_files = {}
        for bank in sorted({h["scriptHeaderBank"] for h in self.kanto}):
            stem = bank.removeprefix("NARC_scr_seq_").removesuffix("_bin")
            name = f"kanto_scripts_init_{stem.removeprefix('scr_seq_').lower()}"
            text = (self.hg / "files/fielddata/script/scr_seq" / f"{stem}.s").read_text()
            (SCRIPTS / f"{name}.s").write_text(self.init_script(text) + "\n")
            init_names.append(name)
            for h in self.kanto:
                if h["scriptHeaderBank"] == bank:
                    self.init_files[h["name"]] = name
        update_meson_files(SCRIPTS / "meson.build", "s", [f"{n}.s" for n in names + init_names])
        update_order(SCRIPTS / "scripts.order", names + init_names)

    def init_script(self, text):
        out = ['#include "macros/scrcmd.inc"', "", ""]
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith(("#", ".")):
                continue
            line = re.sub(r"_EV_scr_seq_\w+_(\d+) \+ 1", lambda m: str(int(m.group(1)) + 1), line)
            if line.endswith(":"):
                out.append(line)
                continue
            cmd, _, rest = line.partition(" ")
            if "std_" in rest:
                # HGSS's Pokémon Center link rooms (wireless, Wi-Fi, the Pokégear).
                self.stats["init scripts dropped"] += 1
                continue
            if cmd == "InitScriptGoToIfEqual":
                var, value, script = [a.strip() for a in rest.split(",")]
                try:
                    var = self.names.value(var)
                    value = self.names.value(value)
                except Unsupported:
                    self.stats["init checks dropped"] += 1
                    continue
                out.append(f"    InitScriptGoToIfEqual {var}, {value}, {script}")
            else:
                out.append(f"    {line}")
        return "\n".join(out)

