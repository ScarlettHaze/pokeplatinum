#!/usr/bin/env python3
"""Import the signs, NPCs, items and scripts of HGSS's Kanto maps.

- Text: each Kanto message bank becomes a Platinum text bank (kanto_text.py).
- Signs: HGSS's signpost graphics replace Platinum's (kanto_signs.py).
- Events: objects, signs, hidden items and triggers join the warps that
  import_kanto_world.py wrote. Sprites come from kanto_sprites.json.
- Scripts: each map's scripts are translated to Platinum's script commands
  (kanto_scripts.py). Scripts that need something Platinum lacks get a stand-in;
  kanto_scripts_report.txt lists them.
- Items: item balls join Platinum's visible items scripts, hidden items its
  hidden items table, and Kanto's specialty marts its marts.
- Flags and vars: HGSS's are given Platinum flags and vars that only Sinnoh's
  map scripts used (kanto_vars_flags.json records which). Kanto's flags that
  HGSS sets when a game starts are set by Platinum's new game script too.

Trainers are not imported yet: trainer NPCs stand where HGSS has them, without
battling.

Run after import_kanto_world.py and import_kanto_sprites.py. Usage:
tools/hgss_import/import_kanto_scripts.py <path-to-pokeheartgold>
"""
