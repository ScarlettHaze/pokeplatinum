"""Bring in the HGSS trainer classes FRLG's trainers need and Platinum lacks,
such as Kanto's Gym Leaders.

Each HGSS class in CLASSES becomes TRAINER_CLASS_KANTO_<class>, appended to
generated/trainer_classes.txt, with HGSS's front sprite
(res/trainers/classes/kanto_<class>), name, gender and prize money. Gym
Leaders, the Elite Four and the Champion count as such in battle
(include/data/kanto_trainer_classes.h).
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

PL = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PL / "tools/hgss_import"))
import narc  # noqa: E402

CLASSES_DIR = PL / "res/trainers/classes"
CLASSES_TXT = PL / "generated/trainer_classes.txt"
NITROGFX = PL / "build/tools/nitrogfx/nitrogfx"
HGSS_TRAINER_PICS = "files/a/0/5/8"
PREFIX = "TRAINER_CLASS_KANTO_"
# Platinum's front sprite layout, which every 80x80 class shares.
SPRITE_TEMPLATE = CLASSES_DIR / "youngster"
GENDERS = {"TRAINER_MALE": "GENDER_MALE", "TRAINER_FEMALE": "GENDER_FEMALE"}

# HGSS classes to bring in, in order (append only: classes keep their IDs).
CLASSES = [
    "TRAINERCLASS_LEADER_BROCK",
]


def class_name(hgss_class):
    return PREFIX + hgss_class.removeprefix("TRAINERCLASS_")


def hgss_class_ids(hg):
    out = {}
    for line in (hg / "include/constants/trainer_class.h").read_text().splitlines():
        m = re.match(r"#define\s+(TRAINERCLASS_\w+)\s+(\d+)\b", line)
        if m:
            out[m.group(1)] = int(m.group(2))
    return out


def import_sprites(hg, ids):
    pics = narc.read_narc(hg / HGSS_TRAINER_PICS)
    for old in CLASSES_DIR.glob("kanto_*"):
        shutil.rmtree(old)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for c in CLASSES:
            n = ids[c]
            out = CLASSES_DIR / class_name(c).removeprefix("TRAINER_CLASS_").lower()
            out.mkdir()
            (tmp / "pic.NCGR").write_bytes(pics[n * 5 + 4])
            (tmp / "pic.NCLR").write_bytes(pics[n * 5 + 1])
            # HGSS stores the scanned sprite back to front, as DP did.
            subprocess.run([NITROGFX, tmp / "pic.NCGR", out / "front_scan.png", "-palette", tmp / "pic.NCLR",
                            "-width", "20", "-encodebacktofront"], check=True)
            Image.open(out / "front_scan.png").crop((0, 0, 80, 80)).save(out / "front.png")
            for f in ("front_cell.json", "front_anim.json"):
                shutil.copy(SPRITE_TEMPLATE / f, out / f)


def import_names(hg, ids, platinum_count):
    names = re.findall(r'<language name="English">(.*?)</language>',
                       (hg / "files/msgdata/msg/msg_0730.gmm").read_text())
    for bank, article in (("trainer_class_names", False), ("trainer_class_names_with_articles", True)):
        path = PL / "res/text" / f"{bank}.json"
        data = json.loads(path.read_text())
        base = data["messages"][:platinum_count]
        prefix = base[0]["id"].rsplit("_", 1)[0]
        for c in CLASSES:
            name = names[ids[c]]
            if article:
                name = ("an " if name[:1] in "AEIOU" else "a ") + name
            base.append({"id": f"{prefix}_{len(base):05d}", "en_US": name})
        data["messages"] = base
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def write_tables(hg):
    genders = {cls: GENDERS.get(value, "GENDER_MALE") for value, cls in
               re.findall(r"(TRAINER_\w+),\s*// (TRAINERCLASS_\w+)", (hg / "src/trainer_data.c").read_text())}
    prize = {c: int(v) for c, v in
             re.findall(r"\.short (TRAINERCLASS_\w+), (\d+)", (hg / "asm/overlay_12_battle_command.s").read_text())}

    def table(fmt, items):
        return "".join(f"    {fmt.format(*i)} \\\n" for i in items)

    def cases(cs):
        return "".join(f"    case {class_name(c)}: \\\n" for c in cs) + "    \n"

    leaders = [c for c in CLASSES if c.startswith("TRAINERCLASS_LEADER_")]
    elite = [c for c in CLASSES if c.startswith("TRAINERCLASS_ELITE_FOUR_")]
    champion = [c for c in CLASSES if c == "TRAINERCLASS_CHAMPION"]
    (PL / "include/data/kanto_trainer_classes.h").write_text(
        "// Generated by tools/frlg_import/frlg_classes.py, do not edit.\n"
        "// The trainer classes FRLG's trainers need, from HGSS.\n\n"
        "#ifndef POKEPLATINUM_DATA_KANTO_TRAINER_CLASSES_H\n"
        "#define POKEPLATINUM_DATA_KANTO_TRAINER_CLASSES_H\n\n"
        "#define KANTO_TRAINER_CLASS_GENDERS \\\n"
        + table("[{}] = {},", [(class_name(c), genders.get(c, "GENDER_MALE")) for c in CLASSES]) + "\n"
        "#define KANTO_TRAINER_CLASS_PRIZE_MUL \\\n"
        + table("[{}] = {},", [(class_name(c), prize.get(c, 4)) for c in CLASSES]) + "\n"
        "#define KANTO_GYM_LEADER_CLASS_CASES \\\n" + cases(leaders) + "\n"
        "#define KANTO_ELITE_FOUR_CLASS_CASES \\\n" + cases(elite) + "\n"
        "#define KANTO_CHAMPION_CLASS_CASES \\\n" + cases(champion) + "\n"
        "#endif\n")


def import_classes(hg):
    hg = Path(hg)
    ids = hgss_class_ids(hg)
    lines = [l for l in CLASSES_TXT.read_text().splitlines() if l and not l.startswith(PREFIX)]
    import_sprites(hg, ids)
    import_names(hg, ids, len(lines))
    write_tables(hg)
    CLASSES_TXT.write_text("\n".join(lines + [class_name(c) for c in CLASSES]) + "\n")
